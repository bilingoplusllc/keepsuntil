def sections_of(html):
    """Заголовок, АТРИБУТЫ абзаца и его текст.

    Атрибуты нужны потому, что окно абзаца теперь спрашивается у разметки:
    заголовок перечисляющего блока называет полку источника и у каждой
    рубрики свой, а окно у них одно.
    """
    out = []
    for m in re.finditer(r"<h2>(.*?)</h2>\s*<p([^>]*)>(.*?)</p>", html, re.S):
        out.append((re.sub(r"<[^>]+>", "", m.group(1)), m.group(2),
                    re.sub(r"<[^>]+>", " ", m.group(3))))
    return out


STD_SPAN = re.compile(r"<span data-std>.*?</span>", re.S)


def own_prose(html):
    """Только СВОЙ текст страницы.

    Из сравнения выпадает ровно две вещи, и обе ОБЪЯВЛЕНЫ:

    * блок метода — он одинаков у всех по построению (prose.CONSTANT_HEADS);
    * фразы из банка prose.STD_BANK, помеченные `<span data-std>`. Указание
      «выброси, не пробуя» у всех скоропортящихся продуктов одно и то же, и
      это правильно: писать одно последствие разными словами — тот самый
      дефект, за который ферма платила. Сто общих слов на страницу уронили
      корпус с 270 до 71, а пометка возвращает их — под гейтом, который
      проверяет ОБЕ стороны и держит потолок доли.
    """
    html = STD_SPAN.sub(" ", html)
    keep = []
    for h2, _attrs, para in sections_of(html):
        if h2 in pr.CONSTANT_HEADS:
            continue
        keep.append(para)
    return " ".join(keep)


# Что снимается с полного текста страницы, и это ВЕСЬ список. Ссылка «к
# содержимому», объявленный общим подвал и объявленные общими фразы банка.
SKIP_LINK = re.compile(r'<a class="skip".*?</a>', re.S)
SHARED_SECT = re.compile(r"<section data-shared>.*?</section>", re.S)
FOOT_DIV = re.compile(r'<footer class="foot">.*?</footer>', re.S)
ENTITY = re.compile(r"&[a-zA-Z]+;|&#[0-9]+;")


def page_text(html):
    """ВЕСЬ видимый текст страницы минус ровно то, что ОБЪЯВЛЕНО общим.

    Гейт близнецов мерил `own_prose` — первый абзац под каждым непостоянным
    H2, около двухсот слов из тысячи семисот. Пара «bagel, fresh baked ~
    macaroons, french» расходилась двумя фразами, имела 0,81 по полному
    видимому тексту и проходила гейт на 0,68: мера, которая смотрит на восьмую
    часть страницы, — не мера страницы.

    Снимается ТОЛЬКО объявленное: три общих раздела (prose.CONSTANT_HEADS),
    фразы банка (`<span data-std>`), подвал (`data-shared` и `.foot`) и ссылка
    «к содержимому». Навигация, подписи полей, величины, строки списков и
    заголовки ОСТАЮТСЯ в сравнении: страница, у которой совпало всё, кроме
    прозы, — близнец, и мерка обязана это видеть.

    Стиль и скрипт вырезаются ПЕРВЫМИ, иначе `text-align:right` считается
    словом «right». Сущности выбрасываются целиком: «&middot;» — не слово, а
    одинаковый у всех страниц шум, который приподнял бы сходство.
    """
    m = re.search(r"<body[^>]*>(.*)</body>", html, re.S)
    t = m.group(1) if m else html
    t = re.sub(r"<(script|style)[^>]*>.*?</\1>", " ", t, flags=re.S)
    t = SKIP_LINK.sub(" ", t)
    t = STD_SPAN.sub(" ", t)
    t = SHARED_SECT.sub(" ", t)
    t = FOOT_DIV.sub(" ", t)
    keep = []
    for part in re.split(r"(?=<section)", t):
        h = re.search(r"<h2>(.*?)</h2>", part, re.S)
        if h and re.sub(r"<[^>]+>", "", h.group(1)).strip() in pr.CONSTANT_HEADS:
            continue
        keep.append(part)
    t = re.sub(r"<[^>]+>", " ", "".join(keep))
    return re.sub(r"\s+", " ", ENTITY.sub(" ", t)).strip()


def shingles(text):
    """СКЕЛЕТ фразы: числа выброшены. Ими подставляют, а совпадает скелет."""
    w = re.findall(r"[a-z][a-z'-]*", text.lower())
    return {tuple(w[i:i + 5]) for i in range(max(0, len(w) - 4))}


def shingles_num(text):
    """Тот же текст С ЧИСЛАМИ. Это ДРУГОЙ вопрос, а не тот же с поправкой:
    две страницы могут разойтись числами и совпасть скелетом, и наоборот.
    Мерок две, и пороги у них разные."""
    w = re.findall(r"[a-z]+|[0-9]+", text.lower())
    return {tuple(w[i:i + 5]) for i in range(max(0, len(w) - 4))}


def jaccard(a, b):
    return len(a & b) / float(len(a | b)) if (a or b) else 0.0


