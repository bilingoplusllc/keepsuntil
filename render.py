def search_index(accepted, adopted=None, page_html=None):
    """Указатель для поиска: строка НА ПРОДУКТ.

    Прежний указатель был строкой на КАЖДОЕ имя (1325 строк) и склеивался по
    ключу без разделителей: две еды с одинаковым ключом теряли одну из
    страниц, и «deli meat» уводил на один продукт из трёх, у которых это имя
    есть. Здесь строка одна на продукт, а все имена, под которыми его знают,
    лежат внутри неё.

    Обе величины для показа собраны ЗДЕСЬ, а не в скрипте: строка, склеенная
    в JS, потребовала бы разделителя внутри кода, а правило репозитория —
    слова живут в разметке. `own` печатается, когда совпало собственное имя,
    `alias` — когда совпало чужое: «mayo» обязан сказать, что это
    «Mayonnaise, commercial».
    """
    out = []
    for it, s, _n in accepted:
        href = "/%s/" % it["slug"]
        # ПОДСКАЗКА ГОВОРИТ ТО ЖЕ, ЧТО И СТРАНИЦА, КУДА ВЕДЁТ. Здесь стояла
        # своя лестница: она брала ВЕРХНИЙ край первой попавшейся ячейки в
        # жёстком порядке, а страница отвечает ОСТОРОЖНЫМ краем связывающего
        # окна. Отсюда 152 строки из 195, расходящиеся с заголовком цели, и
        # 46 строк, обещавших запечатанную величину там, где страница
        # отвечает про вскрытое: «Canned chicken — pantry 5 years» против
        # «3 days in the fridge once opened».
        #   Функция ответа на сайте ОДНА, и её собственная справка называет
        # указатель в числе тех, кто её печатает. Теперь он её и печатает.
        # У продукта с несколькими состояниями окна разные, и печатать в
        # подсказке поиска окно ведущего значило бы обещать в списке одно, а
        # на странице помечать сигналом другое — тот же дефект, что аудит
        # нашёл на 401 строке витрин.
        if pr.multi(it):
            short = "%d kinds" % it["n_states"]
        else:
            # Рубрика вместо срока давала «SOUR CREAM — DAIRY PRODUCTS &
            # EGGS · DAIRY PRODUCTS & EGGS»: одно и то же слово дважды на 15
            # продуктах, у 14 из которых величина на сайте есть.
            short = pr.answer_line(it) or ""
            if short == it["category"]:
                short = ""
        own = title_of(it)
        sep = " %s " % chr(183)
        own_v = sep.join([short, it["category"]] if short else [it["category"]])
        # Имена состояний тоже ищут: «ground beef» живёт строкой «Beef,
        # ground», а не отдельной страницей. Безымянное состояние в указатель
        # не идёт — искать «Bacon (USDA record 63)» никто не станет.
        # ИМЕНА СНЯТЫХ БЛИЗНЕЦОВ ЖИВУТ ЗДЕСЬ. Страницы у них нет, потому что
        # эта её уже описывает; имя обязано вести сюда, иначе «cream cheese»
        # на сайте о сроках хранения не находит ничего.
        # ПЕРЕЕЗЖАЕТ НЕ ВСЯКОЕ ИМЯ. Близнец по прозе — это «страница вышла
        # бы почти такой же», а НЕ «это та же еда»: «Beef broth» снят как
        # близнец «Chicken broth», и перенос имени привёл бы человека,
        # искавшего говяжий бульон, на куриный. Правило берётся у самого
        # сайта: гейт «поиск ведёт на существующее» требует, чтобы имя
        # ВСТРЕЧАЛОСЬ на целевой странице. Значит имя переезжает ровно тогда,
        # когда страница его произносит, и ни разу больше.
        html = (page_html or {}).get(href, "")
        extra = []
        for other in (adopted or {}).get(it["slug"], []):
            for nm in ([title_of(other), pr.short_of(other)]
                       + list(other.get("keywords") or [])):
                nm = (nm or "").strip()
                if not nm:
                    continue
                if re.search(r"(?<![A-Za-z0-9])%s(?![A-Za-z0-9])"
                             % re.escape(nm), html, re.I):
                    extra.append(nm)
        seen, aliases = {own.lower()}, []
        for name in ([pr.kind_title(it, st) for st in pr.states_of(it)
                      if pr.multi(it) and st.get("kind")]
                     + list(it.get("keywords") or [])
                     + [pr.short_of(it)]
                     + extra):
            name = (name or "").strip()
            if not name or name.lower() in seen:
                continue
            if not re.search(r"[a-z0-9]", name.lower()):
                continue
            seen.add(name.lower())
            aliases.append(name)
        out.append([own, href, own_v, aliases])
    return sorted(out, key=lambda r: r[0].lower())


