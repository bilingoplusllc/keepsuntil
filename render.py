def assemble():
    items, ranks, ctx = load_corpus()
    accepted, pages, cat_hubs, stats = build_products(items, ranks, ctx)
    find, _by = findings_pages(accepted)
    pages.update(find)
    pages.update(category_pages(accepted, cat_hubs))
    pages["/all/"] = all_index(accepted, cat_hubs)
    pages["/past-the-date/"] = past_the_date_page(accepted, items)
    pages[METHOD_PATH] = method_page(accepted, items, stats)
    pages["/"] = home(accepted, cat_hubs, ctx)
    pages.update(legal_pages())
    files = {}
    for path, html in pages.items():
        if path.endswith(".html"):
            files[path.lstrip("/")] = html
        else:
            files[(path.strip("/") + "/index.html").lstrip("/")] = html
    # Указатель подставляется ОДИН раз и во ВСЕ страницы: он зависит от
    # окончательного состава корпуса, а состав сходится за три круга отбора,
    # то есть на момент сборки страницы ещё неизвестен.
    html_by_href = {"/%s/" % p[:-len("/index.html")]: v
                    for p, v in files.items() if p.endswith("/index.html")}
    html_by_href["/"] = files.get("index.html", "")
    idx = json.dumps(search_index(accepted, stats.get("принятые имена"),
                                  html_by_href),
                     separators=(",", ":"),
                     ensure_ascii=True)
    assert "<" not in idx, "в указателе поиска знак «<»"
    for p in list(files):
        if p.endswith(".html"):
            assert INDEX_MARK in files[p], "страница без места под указатель"
            files[p] = files[p].replace(INDEX_MARK, idx)
    indexed = [p for p in pages if not p.endswith(".html")]
    files["sitemap.xml"] = sitemap(indexed)
    files["robots.txt"] = robots()
    files["_headers"] = HEADERS
    files["_redirects"] = REDIRECTS
    return files, stats, accepted


def write(files):
    if os.path.isdir(OUT):
        shutil.rmtree(OUT)
    for rel, text in files.items():
        full = os.path.join(OUT, rel.replace("/", os.sep))
        d = os.path.dirname(full)
        if d and not os.path.isdir(d):
            os.makedirs(d)
        io.open(full, "w", encoding="utf-8", newline="\n").write(text)


