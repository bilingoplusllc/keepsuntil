ORG_LD = {"@type": "Organization", "name": SITE, "legalName": PUBLISHER,
          "url": "https://%s/" % DOMAIN}

# Картинки у сайта нет ни одной, и `og:image` поэтому не печатается: адрес
# несуществующей картинки — это и ложь в карточке, и внешний запрос из
# страницы, которая обязана обходиться без единого. Карточка без картинки
# рисуется всеми площадками; карточка с битой — нет.
def og_tags(path, title, desc):
    """Карточка шаринга. Значения ТЕ ЖЕ, что в голове страницы: расхождение
    заголовка в карточке и в выдаче — два разных обещания об одной странице."""
    url = "https://%s%s" % (DOMAIN, path)
    return ('<meta property="og:type" content="website">'
            '<meta property="og:site_name" content="%s">'
            '<meta property="og:locale" content="en_US">'
            '<meta property="og:title" content="%s">'
            '<meta property="og:description" content="%s">'
            '<meta property="og:url" content="%s">'
            '<meta name="twitter:card" content="summary">'
            % (esc(SITE), esc(title), esc(desc), url))


def ld_block(obj):
    """Блок структурных данных. Знак «меньше» экранируется числом: внутри
    скрипта сущности не разбираются, а «</» закрыло бы блок раньше времени."""
    if not obj:
        return ""
    txt = json.dumps(obj, ensure_ascii=True, separators=(",", ":"))
    txt = txt.replace("<", chr(92) + "u003c")
    return '<script type="application/ld+json">%s</script>' % txt


def _measured_rows(html):
    """Пары «место — окно» ровно в том виде, в каком они напечатаны в бланке.

    Схема берёт значения ИЗ ОТДАННОЙ СТРОКИ, а не считает их заново: две
    независимые лестницы для одной величины на этом сайте уже разошлись —
    в бланке стояло «1 month», в абзаце «4 weeks», и оба были верны.
    """
    return [(unescape(k), unescape(v)) for k, v in re.findall(
        r'<li><span class="rk">([^<]*)</span>'
        r'<span class="rv">([^<]*)</span></li>', html)]


def _listed_rows(body):
    """Строки списка ровно в том виде, в каком они НАПЕЧАТАНЫ.

    Схема витрины собирается из отданной разметки, а не из данных заново:
    иначе это две независимые лестницы для одной величины, и они разойдутся —
    ровно так на этом сайте разошлись бирка и проза.
    """
    return [(h, unescape(n)) for h, n in re.findall(
        r'<li><a href="([^"]+)"><span class="n">([^<]*)</span>', body)]


def page_schema(path, title, desc, ptype, body, measured, keywords):
    """Структурные данные страницы. Только НАСТОЯЩИЕ поля.

    Ни рейтингов, ни авторов, ни дат, которых у сайта нет: выдуманная оценка
    в разметке — это заявка на санкции, а выдуманный автор на YMYL-теме —
    ещё и обман. Каждое печатаемое значение обязано встречаться на самой
    странице, и это проверяет гейт.
    """
    url = "https://%s%s" % (DOMAIN, path)
    site = {"@type": "WebSite", "name": SITE, "url": "https://%s/" % DOMAIN}
    base = {"@context": "https://schema.org", "url": url, "name": title,
            "description": desc, "inLanguage": "en-US",
            "publisher": ORG_LD}
    if ptype == "index":
        base.update({"@type": "WebSite"})
        return base
    if ptype == "product":
        rows = [{"@type": "PropertyValue", "name": k, "value": v}
                for k, v in (measured or [])]
        base.update({
            "@type": "Dataset",
            "creator": ORG_LD,
            "isBasedOn": {"@type": "Dataset", "name": SOURCE_NAME,
                          "url": SOURCE_URL},
            "dateModified": CONTENT_DATE.isoformat(),
            "isPartOf": site})
        if rows:
            base["variableMeasured"] = rows
        if keywords:
            base["keywords"] = list(keywords)
        return base
    if ptype == "hub":
        rows = _listed_rows(body)
        base.update({"@type": "ItemList", "isPartOf": site,
                     "numberOfItems": len(rows),
                     "itemListElement": [
                         {"@type": "ListItem", "position": i + 1,
                          "url": "https://%s%s" % (DOMAIN, href), "name": nm}
                         for i, (href, nm) in enumerate(rows)]})
        return base
    base.update({"@type": "WebPage", "isPartOf": site})
    return base


def shell(path, title, desc, body, index=True, script="", ptype="page",
          wide=False, label=None, src="USDA FoodKeeper",
          measured=None, keywords=None, cat=None, related=()):
    """Лист: бирка сверху, отрывной корешок снизу.

    `label` — то, что стоит НАД перфорацией: поля бланка без единого
    предложения прозы. Если его нет, бирка сводится к кромке, а всё
    содержимое живёт в корешке: так устроены витрины и правовые страницы,
    которым нечего печатать на этикетке.
    """
    robots = ("index, follow, max-image-preview:large" if index
              else "noindex, follow")
    # Скрипт ОДИН на страницу. Поиск нужен всюду, календарь — только там, где
    # есть что считать; два тега подряд обошли бы правило «один исполняемый
    # скрипт», написанное затем, чтобы страница не обрастала кодом незаметно.
    code = FINDER_JS + (script or "")
    sc = "<script>%s</script>" % code
    # СЧЁТЧИК СТОИТ В ГОЛОВЕ, и в ней — ниже политики: всё, что напечатано
    # ВЫШЕ <meta http-equiv>, политикой не закрыто. Загрузчик и объявление
    # согласия идут вплотную друг за другом: загрузчик помечен async и
    # вправе исполниться в любой момент после докачки, а согласие обязано
    # отработать ДО первой измерительной команды.
    boot = analytics_boot() if ANALYTICS else ""
    ga = ('<script async src="%s"></script><script>%s</script>'
          % (ANALYTICS_SRC, boot)) if ANALYTICS else ""
    # Политика собирается ИЗ ЭТОЙ ЖЕ страницы: хэш считается от того самого
    # текста, который уходит в тег. Стоит она сразу за кодировкой — раньше
    # стиля, схемы и иконки: то, что напечатано ВЫШЕ политики, ею не
    # закрыто, и это не мелочь порядка, а вся разница.
    csp = ('<meta http-equiv="Content-Security-Policy" content="%s">'
           % csp_value((boot, code), CSS))
    # Поиск и навигация стоят ПЕРВЫМИ в корешке — сразу под ответом. На
    # главной поле поиска и есть ответ, и второе такое же было бы петлёй.
    nav = "" if path == "/" else find_box(path,
                                          ways=nav_ways(path, cat, related))
    stub = nav + body
    lab = label or ""
    band = rail = ""
    # Места ставятся ПО ОБЪЯВЛЕНИЮ, а не по условию в шаблоне: список
    # AD_PLACEMENT читает и гейт, поэтому разметка и объявление не могут
    # разойтись ни в одну сторону.
    slots = AD_PLACEMENT.get(ptype, ()) if ADS else ()
    for n, cls in enumerate(slots):
        block = ad_slot(cls, path, n)
        if cls == "ad-rail":
            # Рельса — ребёнок ЛИСТА, сразу под перфорацией: выше неё вся
            # бирка целиком. В бирке она стоила 74px первого экрана
            # телефона, а бирка обязана помещаться на один экран; на
            # десктопе сетка кладёт её в колонку бирки, под саму бирку,
            # то есть ровно туда, где разбор облика нашёл пустое место.
            rail = block
        elif cls == "ad-flow":
            stub = _insert_after_sections(stub, AD_FLOW_AFTER, block)
        else:
            band = '<div class="adband">%s</div>' % block
    tag = strip_row(path, src) + lab
    schema = page_schema(path, title, desc, ptype, body, measured, keywords)
    return """<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
%(csp)s
<title>%(title)s</title>
<meta name="description" content="%(desc)s">
<meta name="robots" content="%(robots)s">
<meta name="page-type" content="%(ptype)s">
<link rel="canonical" href="https://%(domain)s%(path)s">
<link rel="icon" href="data:image/svg+xml,%(icon)s">
%(og)s%(ld)s%(ga)s<style>%(css)s</style>
</head>
<body>
<a class="skip" href="#stub">Skip to the notes</a>
<main class="sheet">
<div class="label">%(tag)s</div>
%(perf)s%(rail)s<div class="stub" id="stub">%(stub)s%(foot)s</div>
</main>%(band)s%(idx)s%(sc)s%(loader)s
</body>
</html>
""" % {"title": esc(title), "desc": esc(desc), "domain": DOMAIN, "path": path,
       "idx": index_block(),
       "icon": ICON, "css": CSS, "tag": tag, "stub": stub,
       "perf": perf_row(ptype), "foot": foot_row(path), "band": band,
       "rail": rail,
       "og": og_tags(path, title, desc), "ld": ld_block(schema),
       "loader": ad_loader(len(slots)), "ga": ga,
       "robots": robots, "sc": sc, "ptype": ptype, "csp": csp}


