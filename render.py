def _bag(it):
    """Слова, под которыми продукт вообще известен: имя, имена состояний и
    ключевые слова источника."""
    import prose as _pr
    parts = [it["name"], " ".join(it.get("keywords") or [])]
    parts += [(st.get("kind") or "") for st in _pr.states_of(it)]
    return set(re.findall(r"[a-z0-9]+", " ".join(parts).lower()))


def head_matches(items):
    """Термин спроса -> продукты, которые под него подходят.

    Совпадение по СЛОВАМ, а не по подстроке: «milk» не должен подхватывать
    «buttermilk», а «ground beef» обязан находить «Beef» с ключевым словом
    «ground», потому что отдельной записи «Ground beef» в источнике нет.
    """
    out = {}
    for term in HEAD_TERMS:
        need = set(re.findall(r"[a-z0-9]+", term.lower()))
        out[term] = [it for it in items if need <= _bag(it)]
    return out


def head_rank(it, matches):
    for i, term in enumerate(HEAD_TERMS):
        if any(x["slug"] == it["slug"] for x in matches[term]):
            return i
    return len(HEAD_TERMS)


def cat_slug(name):
    s = re.sub(r"[^a-z0-9]+", "-", name.lower()).strip("-")
    return re.sub(r"-+", "-", s)


