def near_list(rows, lead=False):
    """Единственный вид ссылки с величиной: имя слева, величина справа.

    Строка — это (адрес, имя, величина) или (адрес, имя, величина, оговорка).
    Оговорка печатается ВТОРОЙ строкой величины: предложение в 44 знака,
    поставленное в колонку значений, ломало строку бланка пополам.

    `lead=True` помечает ПЕРВУЮ строку сигналом. На рейтинге это и есть
    ответ страницы — ровно то же, что помечено сигналом на бирке товара.
    """
    out = []
    for row in rows:
        href, name, val = row[0], row[1], row[2]
        note = row[3] if len(row) > 3 else ""
        out.append('<li><a href="%s"><span class="n">%s</span>'
                   '<span class="v">%s%s</span></a></li>'
                   % (href, esc(name), esc(val),
                      ('<small>%s</small>' % esc(note)) if note else ""))
    # Пометка стоит на СПИСКЕ, а не на строке: строка списка читается семью
    # регулярками гейтов дословно как `<li><a href=...>`, и класс на ней
    # молча отнял бы у них хватку — счётчик строк витрины сразу насчитал 59
    # из 60. Сигнал вешает CSS через :first-child.
    return ('<ul class="near" role="list"%s>%s</ul>'
            % (' data-lead="1"' if lead else "", "".join(out)))


def also_line(it):
    """Как ЕЩЁ называется эта еда, словами источника.

    FoodKeeper держит для каждой записи список ключевых слов — это и есть то,
    что человек пишет в поиске: «mayo», «apple pie», «baby carrot». Поиск на
    главной по ним ищет, и страница обязана их нести: иначе за «Almond»
    человека приводят на страницу, где такого слова нет, и переход выглядит
    промахом.
    """
    terms = index_terms(it)
    if not terms:
        return ""
    return ('<p class="quiet">USDA index terms: %s</p>'
            % esc(", ".join(terms)))


def index_terms(it):
    """Ключевые слова источника — ОДНА функция на печать и на схему.

    Пока их считали дважды, это были бы две лестницы для одной величины, и
    схема обещала бы в разметке слова, которых на странице нет.
    """
    own = title_of(it)
    seen, terms = set(), []
    for k in (it.get("keywords") or []):
        k = k.strip()
        if not k or k.lower() == own.lower() or k.lower() in seen:
            continue
        seen.add(k.lower())
        terms.append(k)
    return sorted(terms, key=str.lower)


def as_sections(html):
    """Тело, написанное сплошняком, режется на разделы по заголовкам.

    Правовые страницы остались от облика «статья»: заголовки и абзацы подряд,
    без единого раздела. В корешке раздел — носитель отбивки и линии, и без
    него текст шёл встык к краю листа. Видно это было только в браузере: все
    30 гейтов читают разметку и про отбивку ничего не знают.
    """
    parts = re.split(r"(?=<h2>)", html)
    return "".join(sect(p) for p in parts if p.strip())


def sect(html):
    """Блок корешка — раздел. Пустой блок раздела не заводит: пустая коробка
    в разметке ломает правила «последний теряет линию», как уже случилось с
    540 невидимыми рекламными местами на соседнем сайте."""
    return ("<section>%s</section>" % html) if html else ""


def product_page(it, s, ctx, nbs, cat_hubs, rel=()):
    """Лист продукта: бирка с ответом, корешок со всем остальным.

    Над перфорацией нет ни одного предложения прозы — только поля бланка,
    величины и одно поле даты. Всё, что раньше стояло девятью разделами
    подряд, ушло в корешок и стало вторичным ЯВНО, а не по случайности.
    """
    t = title_of(it)
    multi = s["n_states"] > 1
    # Заголовок собирается ОДНОЙ функцией, и первым в нём стоит тот же ответ,
    # что печатают указатель и витрины: см. prose.head_title.
    head = fit_title(pr.head_title(it, s, fit_title))

    # Места считаются по ВСЕМ состояниям: описание вводит страницу целиком.
    fam = pr.families(it)
    places = [w for k, w in (("fridge", "refrigerator"), ("freeze", "freezer"),
                             ("pantry", "pantry")) if k in fam]
    where = pr.listing(places) if places else "the places the USDA rates"
    gain = s.get("gain")
    way = pr.gain_way(gain.r) if gain else None
    # Глагол согласуется с ИМЕНЕМ: 66 описаний в выдаче читались «How long
    # Apples keeps in the fridge». Согласование считает одна функция на весь
    # сайт, и её проверяет отдельный гейт.
    kw = pr.keeps_word(t)
    if multi:
        desc = pr.multi_desc(it, s)
    elif way == "up":
        # Знаменатель НАЗВАН и в описании выдачи: «5.7 times longer than the
        # refrigerator» стояло там, где бирка делила на шкаф.
        desc = ("How long %s %s in the %s, and what freezing buys you: "
                "%s longer than %s, from the USDA figures."
                % (t, kw, where, pr.mult(gain.r),
                   pr.DEN_PHRASE[gain.den_key]))
    elif way == "down":
        desc = ("How long %s %s in the %s, and why the freezer is the "
                "shorter option for it, from the USDA figures."
                % (t, kw, where))
    elif way == "flat":
        desc = ("How long %s %s in the %s: the USDA gives it the same "
                "window frozen as refrigerated." % (t, kw, where))
    elif s.get("open"):
        desc = ("How long %s %s in the %s, and what opening the package "
                "costs: the USDA figures with the comparison between them."
                % (t, kw, where))
    else:
        desc = ("How long %s %s in the %s, every figure the USDA "
                "publishes for it, turned into a date on your calendar."
                % (t, kw, where))
    # Ответ стоит В НАЧАЛЕ описания, и это ТА ЖЕ строка, что в заголовке и в
    # указателе. У 25 продуктов имя длиннее заголовка целиком («Commercial
    # bread products, including pan breads, flat breads, rolls and buns»), и
    # ответ из заголовка вытесняется именем — но из выдачи он не исчезает
    # ни у одной страницы.
    answer = pr.answer_value(it)
    if answer:
        desc = "%s: %s. %s" % (t, answer, desc)
    desc = fit_desc(desc)

    # Бланк собирается ОДИН раз: из этой же строки берутся пары для схемы,
    # поэтому напечатанное и размеченное совпадают по построению.
    table = pr.table_block(it, s)
    # Сравнения стоят первыми блоками разбора: полями бланка, а не разделами,
    # потому что они и есть поля — подпись, величина, отсчёт. Первым идёт
    # самое длинное окно (переехало с первого экрана: это сравнение, а не
    # ответ), вторым — кратность.
    stub = pr.longest_box(it, s) + pr.cost_box(it) + "".join(sect(x) for x in (
        pr.kinds_block(it, s),
        pr.difference_block(it, s),
        table,
        pr.says_block(it),
        pr.safety_block(it),
        pr.tips_block(it),
        pr.date_block(it, s),
        # Что окно ЗНАЧИТ и что делать, когда оно вышло, стоят сразу под
        # датой: человек с открытым холодильником доходит до них, а до
        # рейтингов и соседей — нет.
        pr.means_block(it, s),
        pr.now_what_block(it, s),
        pr.wrong_place_block(it, s),
        pr.scope_block(it),
        pr.rank_block(it, s, ctx),
        pr.neighbours_block(it, s, nbs),
        # Блоки ГЛУБИНЫ. Объём берётся не водой, а тем, чего на странице до
        # сих пор не было: набор ячеек как признак записи, полка источника,
        # шаг вверх по сроку в том же отделе и сама запись FoodKeeper.
        # Каждый называет другие продукты ПОИМЁННО — это те слова, которых
        # нет ни на одной другой странице, и именно они держат сходство
        # внизу, пока страница растёт.
        pr.cohort_block(it, s, ctx),
        pr.shelfmates_block(it, s, ctx),
        pr.swap_block(it, s, ctx),
        pr.record_block(it, s, ctx, DATA_VINTAGE),
        pr.method_block(DATA_VINTAGE),
        also_line(it)))
    # Рубрика на кромке перестала быть мёртвым текстом: 0 страниц продуктов
    # из 221 вели в свою рубрику, и слово «Produce · USDA FoodKeeper» стояло
    # там же, где стоит теперь ссылка вверх.
    cslug = cat_slug(it["category"])
    cat = (("/category/%s/" % cslug, it["category"])
           if cslug in cat_hubs else None)
    strip = ((('<a href="%s">%s</a>' % (cat[0], esc(cat[1]))) if cat
              else esc(it["category"]))
             + " &middot; USDA FoodKeeper")
    return shell("/%s/" % it["slug"], head, desc, stub,
                 script=pr.DATE_TOOL_JS, ptype="product",
                 label=pr.label_fields(it, s),
                 measured=_measured_rows(table), keywords=index_terms(it),
                 src=strip, cat=cat,
                 related=[("/%s/" % x["slug"], pr.short_of(x)) for x in rel])


# Потолок заголовка тот же, что проверяет гейт: 60 знаков В ОТДАННОМ виде.
# Кавычка в имени источника разворачивается в «&quot;» и добавляет пять
# знаков, которых в исходной строке не видно.
TITLE_MAX = 60


def fit_title(head):
    """Заголовок обрезается по границе слова и меряется ПОСЛЕ экранирования."""
    if len(esc(head)) <= TITLE_MAX:
        return head
    words = head.split()
    while len(words) > 1 and len(esc(" ".join(words))) > TITLE_MAX:
        words.pop()
    return " ".join(words).rstrip(" ,:;")


def fit_desc(desc, limit=158):
    """Описание не обрывается посреди слова.

    Прежде стояло `desc[:158]`, и 49 описаний из 221 кончались обрубком:
    «from the USDA figur». В выдаче это единственный текст, который человек
    читает до перехода.

    Длина меряется ПОСЛЕ экранирования, как её меряет гейт: кавычка в имени
    источника разворачивается в «&quot;» и добавляет пять знаков, которых в
    исходной строке не видно. Ровно на этом однажды прошло описание в 178
    знаков.
    """
    if len(esc(desc)) <= limit:
        return desc
    cut = desc
    while cut and len(esc(cut)) > limit:
        cut = cut[:-1]
    dot = max(cut.rfind(". "), cut.rfind("! "), cut.rfind("? "))
    if dot >= 60:
        return cut[:dot + 1]
    space = cut.rfind(" ")
    # Многоточие ставится ЗНАКОМ, а не сущностью: описание уходит через
    # экранирование, и «&hellip;» печаталось в выдаче как «&amp;hellip;».
    return (cut[:space] if space >= 60 else cut).rstrip(" ,;:") + chr(8230)


def pick_neighbours(it, items):
    """Соседи ПО ДАННЫМ: та же категория, ближайший срок. Алфавитный сосед —
    не сосед: перелинковка по алфавиту не помогает ни человеку, ни роботу."""
    d = fk.shelf_days(it)
    # Соседи считаются между ПРОДУКТАМИ. Пока единицей была строка источника,
    # соседями продукта оказывались его же собственные состояния: ссылка вела
    # на почти дословный близнец, а близнец не выпускался — тупик и близнец
    # одним движением.
    same = [x for x in items
            if x["category"] == it["category"] and x["slug"] != it["slug"]
            and fk.shelf_days(x) is not None]
    # У продукта, которому источник не дал НИ ОДНОГО числа, ближе быть не к
    # чему, и «ближайший» здесь значит «та же полка, начиная с самых коротких
    # сроков»: страница обязана вывести на еду, которую источник оценивает, а
    # осторожная сторона у списка одна.
    if d is None:
        same.sort(key=lambda x: (fk.shelf_days(x), x["id"]))
    else:
        same.sort(key=lambda x: (abs(fk.shelf_days(x) - d), x["id"]))
    out = []
    for x in same:
        xd = fk.shelf_days(x)
        v, note = pr.listing_parts(x)
        why = ("keeps exactly as long" if d is not None and abs(xd - d) < 0.01
               else "keeps %s" % v)
        out.append({"slug": x["slug"], "title": title_of(x), "why": why,
                    "note": "" if (d is not None
                                   and abs(xd - d) < 0.01) else note,
                    "days": xd, "h": pr.shelf_h(x), "id": x["id"]})
    return out


