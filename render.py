#
# Слово, встречающееся у слишком многих продуктов, связью не считается:
# «commercially» и «packaged» стоят у сотни записей и не значат ничего.
# Порог — по ЧАСТОТЕ в корпусе, а не по написанному от руки списку.
REL_MAX_DF = 12
REL_POOL = 40


def rel_tokens(it):
    """Слова ИМЕНИ, а не ключевые слова источника.

    Замерено на собранном: по ключевым словам «Milk» роднился с «Ham» и
    «Flavored or herb mixes» — через «canned» и «flavored», которые стоят у
    сотни записей и не значат ничего. Имя — то, чем еда называется.
    """
    return {w for w in re.findall(r"[a-z0-9]+", it["name"].lower())
            if len(w) > 2}


def related_index(items):
    tok = {it["id"]: rel_tokens(it) for it in items}
    df = {}
    for st in tok.values():
        for w in st:
            df[w] = df.get(w, 0) + 1
    return {k: {w for w in st if df[w] <= REL_MAX_DF} for k, st in tok.items()}


def pick_related(it, items, tok):
    """Два разных родства, вперемежку: по слову имени и по полке.

    Порознь ни одно не даёт того, что человеку нужно. По слову у молока
    выходят одни «X milk», по полке — маргарин и сыр (их и так печатает блок
    соседей). Вперемежку выходит и то и другое.
    """
    d = fk.shelf_days(it)
    mine = tok[it["id"]]
    by_word, by_shelf = [], []
    for x in items:
        if x["id"] == it["id"]:
            continue
        dx = fk.shelf_days(x)
        gap = (abs(dx - d) if (dx is not None and d is not None) else 1e9)
        shared = len(mine & tok[x["id"]])
        if shared:
            by_word.append((-shared, gap, int(x["id"]), x))
        if x["category"] == it["category"]:
            by_shelf.append((gap, int(x["id"]), x))
    by_word.sort(key=lambda r: r[:3])
    by_shelf.sort(key=lambda r: r[:2])
    a = [r[-1] for r in by_word]
    # Ближайшие по полке уже напечатаны блоком соседей — тем же порядком, той
    # же функцией сравнения. Брать их сюда значило бы назвать одну ссылку
    # дважды, и вбок не вело бы никуда нового.
    b = [r[-1] for r in by_shelf][NEIGHBOURS[1]:]
    out, seen = [], set()
    for i in range(REL_POOL):
        for src in (a, b):
            if i < len(src) and src[i]["id"] not in seen:
                seen.add(src[i]["id"])
                out.append(src[i])
    return out[:REL_POOL]




