def load_corpus():
    """Корпус — ПРОДУКТЫ, а не строки источника.

    Замер 05.09.2026: 100 имён из 466 несут больше одной строки, и в
    одноимённых группах сидят 292 строки из 658. Порознь эти строки почти
    дословные близнецы, и гейт близнецов честно выбрасывал их все — то есть
    всю голову ниши. Он работал правильно; неверна была единица.
    """
    rows = fk.load()
    for it in rows:
        it["slug"] = fk.slug(it)
    seen, uniq = set(), []
    for it in rows:
        if it["slug"] in seen:
            continue
        seen.add(it["slug"])
        uniq.append(it)
    items = fk.merge_by_name(uniq)
    fk.assign_slugs(items)
    assign_short(items)
    ranks = fk.rank_in_category(items)
    return items, ranks, pr.context(items, ranks)


def assign_short(items):
    """Короткое имя для показа — ОДНО на продукт, и оно обязано остаться
    различающим.

    Замерено на телефоне: имя источника «Canned goods, low acid, such as meat,
    poultry, fish, gravy, stew, soups, beans, carrots, corn, pasta, peas,
    potatoes, spinach» набиралось заголовочным кеглем в семь строк — 197px, —
    и первый крупный ответ уезжал на 414-й пиксель. Хвост после запятой это
    перечень примеров, а не имя: он уходит строкой ниже, мелким, ЦЕЛИКОМ.

    Сокращение отменяется, когда обрубок перестаёт различать два продукта:
    «Shrimp, crayfish» и «Shrimp, shellfish» обязаны остаться разными
    заголовками, иначе две страницы получают один и тот же H1.
    """
    cand = {}
    for it in items:
        c = re.split(r"[,(]", it["name"])[0].strip().rstrip(" -")
        cand[it["id"]] = c or it["name"]
    taken = {}
    for it in items:
        taken[cand[it["id"]].lower()] = taken.get(cand[it["id"]].lower(), 0) + 1
    for it in items:
        c = cand[it["id"]]
        it["short"] = c if taken[c.lower()] == 1 else it["name"]


def _one_pass(prepared, ctx, cat_hubs, live, drop, merge=None):
    """Один круг: собрать страницы кандидатов и прогнать постраничные гейты.
    Соседи берутся ТОЛЬКО среди live — кандидатов этого круга."""
    pages, accepted, index = {}, [], []
    worst = 0.0
    for it, all_nbs, all_rel in prepared:
        if it["id"] not in live:
            continue
        nbs = [x for x in all_nbs if x["id"] in live][:NEIGHBOURS[1]]
        if len(nbs) < NEIGHBOURS[0]:
            drop("меньше %d соседей среди выпущенных" % NEIGHBOURS[0])
            continue
        # Вбок — ДРУГИЕ продукты, чем соседи по сроку: два одинаковых списка
        # под разными подписями были бы одной ссылкой, названной дважды.
        shown = {x["slug"] for x in nbs}
        rel = [x for x in all_rel
               if x["id"] in live and x["slug"] not in shown][:RELATED_SHOWN]
        s = pr.shape(it, ctx)
        html = product_page(it, s, ctx, nbs, cat_hubs, rel)
        bad = None
        for h2, attrs, para in sections_of(html):
            n = pr.wc(para)
            lo, hi = pr.window_for(h2, attrs)
            if not lo <= n <= hi:
                bad = "абзац вне окна %d–%d слов" % (lo, hi)
                break
            if not re.search(r"[0-9]", para):
                bad = "абзац без числа"
                break
        if bad:
            drop(bad)
            continue
        sh = shingles(own_prose(html))
        pt = page_text(html)
        ph, pk = shingles_num(pt), shingles(pt)
        if not sh or not ph or not pk:
            drop("пустая своя проза")
            continue
        twin, jmax, twin_of = False, 0.0, None
        # Три сравнения, потому что вопроса три: своя проза, вся страница с
        # числами и скелет всей страницы. Отбор обязан считать РОВНО то, что
        # потом посчитает гейт, иначе сборка выпускает то, что гейт снимет.
        for other, oh, ok, oslug in index:
            j = jaccard(sh, other)
            if j > jmax:
                jmax = j
            # Порог ВКЛЮЧЁН: пара ровно в 0,700 выходила в выкладку, и в
            # отчёте сборки честно стояло «максимальное сходство 0.700 при
            # пороге 0.70». Граница, которую можно занять, — не граница.
            if (j >= TWIN_MAX or jaccard(ph, oh) >= PAGE_TWIN_MAX
                    or jaccard(pk, ok) >= PAGE_SKEL_MAX):
                twin, twin_of = True, oslug
                break
        if twin:
            # ИМЯ СНЯТОГО ОБЯЗАНО ОСТАТЬСЯ НАХОДИМЫМ. Гейт близнецов снял
            # 141 страницу, и вместе со страницами из указателя исчезли 168
            # имён — среди них «Cream cheese», «Cottage cheese»,
            # «Buttermilk», «Whipped cream», «Lamb». Человек на сайте о
            # сроках хранения вводил «cream cheese» и не получал НИЧЕГО,
            # хотя ответ на сайте есть — просто под другим именем.
            #   Близнец — это не «еды нет», а «еда описана соседней
            # страницей». Значит имя переезжает к ней, а не выбрасывается.
            if merge is not None and twin_of:
                merge(it, twin_of)
            drop("близнец уже выпущенной страницы")
            continue
        worst = max(worst, jmax)
        index.append((sh, ph, pk, it["slug"]))
        pages["/%s/" % it["slug"]] = html
        accepted.append((it, s, nbs))
    return pages, accepted, worst


def _hubs_of(accepted):
    n = {}
    for it, _s, _nb in accepted:
        c = cat_slug(it["category"])
        n[c] = n.get(c, 0) + 1
    return {c for c, k in n.items() if k >= MIN_CAT_HUB}


def build_products(items, ranks, ctx):
    """Отбор и выпуск страниц. Мера успеха — не сколько собрано, а сколько
    ПЕРЕЖИЛО гейты."""
    pre = {}

    def prefilter(why):
        pre[why] = pre.get(why, 0) + 1

    prepared = []
    # Порядок рассмотрения — по тому, сколько у записи есть ЧТО СКАЗАТЬ:
    # сперва продукты с несколькими состояниями, потом с большим числом
    # заполненных ячеек. Гейт близнецов принимает первого из пары, и
    # переживать столкновение должна более содержательная страница, а не та,
    # у которой ниже номер записи в источнике: отбор по номеру — это отбор
    # случайностью, и он оставил корпус без головы ниши.
    matches = head_matches(items)
    rel_tok = related_index(items)

    def richness(x):
        cells = sum(len(st["slots"]) for st in pr.states_of(x))
        return (head_rank(x, matches), -x.get("n_states", 1), -cells,
                int(x["id"]))

    def _said(x):
        """Источник ответил СЛОВАМИ вместо числа: «Package use-by date»."""
        return any((st.get("says") or {}) for st in pr.states_of(x))

    def _typed_word(x):
        """Простое имя продукта И ЕСТЬ то слово, которое набирают."""
        own = set(re.findall(r"[a-z0-9]+", x["name"].lower()))
        return any(set(re.findall(r"[a-z0-9]+", t.lower())) <= own
                   for t in HEAD_TERMS)

    for it in sorted(items, key=richness):
        # ОТВЕТ СЛОВАМИ — ТОЖЕ ОТВЕТ. Отбор пускал только числа, и слово
        # «sour cream» отдавало 404 при том, что источник по нему говорит:
        # смотри дату на упаковке, а морозить не советует. Страница, которая
        # честно печатает «числа нет, вот что источник говорит вместо него, и
        # вот соседи, которым число он дал», полезнее пустоты. Открыто это
        # ровно для слов спроса и ровно там, где источник сказал хоть что-то:
        # ниша не набирается страницами, которым сказать нечего.
        # СТРАНИЦА-ВЫБОР — не «без срока». Своих ячеек у неё нет нарочно
        # (fk.PLAIN_MEANS = SPLIT: простое слово не значит одного вида), а
        # окна есть у каждого её вида, и это ровно голова ниши — beef, ham,
        # cheese, pies. Отбор по продуктовым ячейкам вынес их все десять на
        # первом же прогоне: /beef/ отдавал 404 при двадцати заполненных
        # ячейках на странице.
        pick = pr.split(it) and pr.worst_cell(it) is not None
        if (fk.shelf_days(it) is None and not pick
                and not (_typed_word(it) and _said(it))):
            prefilter("нет ни одного срока вне морозилки")
            continue
        nbs = pick_neighbours(it, items)
        if len(nbs) < NEIGHBOURS[0]:
            prefilter("меньше %d соседей по данным — страница была бы тупиком"
                      % NEIGHBOURS[0])
            continue
        prepared.append((it, nbs, pick_related(it, items, rel_tok)))

    live = {it["id"] for it, _n, _r in prepared}
    hubs = _hubs_of([(it, None, None) for it, _n, _r in prepared])
    pages, accepted, worst, rounds, last, first = {}, [], 0.0, 0, {}, {}
    # Кто чьим близнецом оказался. Копится ПО ВСЕМ КРУГАМ: снятый в первом
    # круге больше не оценивается никогда, и записать его не в тот момент
    # значит не записать вовсе. Первая запись побеждает — она сделана тогда,
    # когда предмет ещё сравнивался.
    merges = {}

    def note_merge(item, other_slug):
        merges.setdefault(item["slug"], (other_slug, item))

    for rnd in range(12):
        last = {}
        pages, accepted, worst = _one_pass(
            prepared, ctx, hubs, live,
            lambda w: last.__setitem__(w, last.get(w, 0) + 1),
            note_merge)
        rounds = rnd + 1
        if rnd == 0:
            first = dict(last)
        got = {it["id"] for it, _s, _n in accepted}
        new_hubs = _hubs_of(accepted)
        if got == live and new_hubs == hubs:
            break
        live, hubs = got, new_hubs
    else:
        raise AssertionError("отбор не сошёлся за 12 кругов")

    # РАЗРЕШЕНИЕ ЦЕПОЧКИ. Страница, к которой переехало имя, могла сама
    # оказаться близнецом и уйти на следующем круге. Тогда имя идёт дальше по
    # цепочке, пока не упрётся в выжившую; если не упрётся — имя остаётся без
    # дома, и это честнее, чем ссылка в никуда.
    alive = {it["slug"] for it, _s, _n in accepted}
    adopted, orphans = {}, []
    for slug, (target, item) in sorted(merges.items()):
        seen_chain, cur = {slug}, target
        while cur and cur not in alive and cur in merges and cur not in seen_chain:
            seen_chain.add(cur)
            cur = merges[cur][0]
        if cur in alive:
            adopted.setdefault(cur, []).append(item)
        else:
            orphans.append(item)

    # Показываем отказы ПЕРВОГО круга: в последнем их ноль по построению —
    # состав уже сошёлся, — и отчёт «отклонено: 34» скрывал бы, что до
    # выпуска не дошли четыреста продуктов и по каким именно причинам.
    # Термины спроса, у которых продукт есть, а страницы нет: их снял гейт
    # близнецов, и это ЗАМЕР, а не поломка. Печатается на каждой сборке —
    # молчащий пробел в голове ниши мы уже проходили.
    live_slugs = {it["slug"] for it, _s, _n in accepted}
    gap = []
    for term in HEAD_TERMS:
        need = set(re.findall(r"[a-z0-9]+", term.lower()))
        for x in matches[term]:
            if fk.shelf_days(x) is None or x["slug"] in live_slugs:
                continue
            # Пробелом считается только совпадение по САМОМУ ИМЕНИ: продукт,
            # подошедший под термин ключевым словом, отчитываться за него не
            # может.
            if need <= set(re.findall(r"[a-z0-9]+", x["name"].lower())):
                gap.append((term, x["slug"]))
    # Без округления. Округление до трёх знаков превращало 0,6996 в 0,7, и
    # отчёт печатал «максимальное сходство 0.7000 при пороге 0.70» — то есть
    # сам сообщал, что порог занят, ровно там, где отбор его занять не даёт
    # (условие снятия включает границу). Число, которое печатают, округляет
    # печать, а не источник.
    stats = {"всего": len(items), "выпущено": len(accepted), "кругов": rounds,
             "максимальное сходство": worst, "отклонено": dict(pre),
             "голова без страниц": gap,
             "принятые имена": adopted,
             "имена без дома": orphans}
    for k, v in first.items():
        stats["отклонено"][k] = stats["отклонено"].get(k, 0) + v
    later = len(items) - len(accepted) - sum(stats["отклонено"].values())
    if later > 0:
        stats["отклонено"]["сняты на последующих кругах отбора"] = later
    return accepted, pages, hubs, stats


# ------------------------------------------------------------------- витрины

def rank_table(rows, lead=True):
    """Витрина рейтинга. Ведущая строка помечена сигналом: это ответ,
    ради которого рейтинг построен."""
    return near_list([(("/%s/" % r[0],) + tuple(r[1:])) for r in rows],
                     lead=lead)


def findings_pages(accepted):
    """Три вычисленных рейтинга. Это не «страницы ради страниц»: каждая отвечает
    на вопрос, которого в источнике нет, и раздаёт ссылки вглубь."""
    out = {}
    by = {it["slug"]: (it, s) for it, s, _n in accepted}

    gain = sorted((s["gain"].r, it["slug"], title_of(it), s["gain"])
                  for it, s, _n in accepted if s["gain"])[::-1][:HUB_ROWS]
    # Обе стороны деления НАЗВАНЫ и здесь. «5 years to 2 days» без имён мест
    # читалось как один и тот же шкаф до и после, а знаменателем мог быть
    # холодильник.
    rows = [(sl, t, "%s longer frozen" % pr.mult(g.r),
             "than %s (%s to %s)"
             % (pr.DEN_PHRASE[g.den_key],
                human(g.den, pr.u(by[sl][0], g.den_key)),
                human(g.num, pr.u(by[sl][0], g.num_key))))
            for _r, sl, t, g in gain]
    pool = len([1 for it, s, _n in accepted if s["gain"]])
    body = (sect(rank_table(rows))
            + "<section><h2>How this list is built</h2>"
              "<p>Of the %d foods here where the USDA publishes both a "
              "freezer figure and at least one figure outside the freezer, "
              "these %d gain the most from freezing. Each multiplier divides "
              "the freezer figure by the longest window that food has without "
              "a freezer, so the gain is measured against the best you could "
              "do otherwise and not against the worst. The division is ours: "
              "the source prints the ranges and never divides one by another."
              "</p></section>" % (pool, len(rows)))
    out["/freezer-gains/"] = shell(
        "/freezer-gains/", "Where freezing buys the most time",
        "The foods that gain most from the freezer, ranked by how many times "
        "longer they keep frozen than at their best without one.", body,
        wide=True,
        ptype="hub", src="Computed from USDA figures",
        label=hub_label("Ranking", "Where the freezer buys most",
                        "top %d of %d &middot; frozen against the best "
                        "window without a freezer" % (len(rows), pool)))

    op = sorted((s["open"].r, it["slug"], title_of(it), s["open"])
                for it, s, _n in accepted if s["open"])[::-1][:HUB_ROWS]
    rows = [(sl, t, "%s shorter once open" % pr.mult(o.r),
             "(at best %s %s against at best %s %s)"
             % (human(o.num), pr.SHORT_WHERE[o.num_key],
                human(o.den), pr.SHORT_WHERE[o.den_key]))
            for _r, sl, t, o in op]
    pool = len([1 for it, s, _n in accepted if s["open"]])
    body = (sect(rank_table(rows))
            + "<section><h2>How this list is built</h2>"
              "<p>These %d foods lose the most when the seal is broken. Each "
              "figure is the sealed life divided by the life after opening, a "
              "comparison the FoodKeeper data supports but never makes.</p>"
              "</section>" % len(rows))
    out["/after-opening/"] = shell(
        "/after-opening/", "What opening the package costs",
        "The foods that lose the most shelf life once opened, ranked by how "
        "many times shorter they keep after the seal is broken.", body,
        wide=True, ptype="hub", src="Computed from USDA figures",
        label=hub_label("Ranking", "What opening costs",
                        "top %d of %d &middot; sealed against opened"
                        % (len(rows), pool)))

    # СОРТИРОВКА ПО ТОМУ ЧИСЛУ, КОТОРОЕ НАПЕЧАТАНО В СТРОКЕ. Пока рейтинг
    # шёл по fk.shelf_days (лучшее по всем состояниям), а строка печатала
    # ведущее, порядок на странице был виден как сломанный: восемь пар из 59
    # шли по возрастанию вопреки заголовку.
    lg = sorted(((pr.listing_days(it), it["slug"], title_of(it),
                  pr.listing_parts(it))
                 for it, s, _n in accepted if s["days"]),
                key=lambda x: -x[0])[:HUB_ROWS]
    rows = [(sl, t, h[0], h[1]) for _d, sl, t, h in lg]
    body = (sect(rank_table(rows))
            + "<section><h2>How this list is built</h2>"
              "<p>Ranked by the figure printed in each row: the longest the "
              "USDA publishes for that food outside the freezer, for the kind "
              "this page leads with, so pantry and refrigerator "
              "compete on the same scale. The freezer is excluded on purpose: "
              "it flattens almost everything and stops the ranking saying "
              "anything.</p></section>")
    out["/longest-keeping/"] = shell(
        "/longest-keeping/", "What keeps longest without a freezer",
        "Foods ranked by the longest storage time the USDA publishes outside "
        "the freezer.", body, wide=True,
        ptype="hub", src="Computed from USDA figures",
        label=hub_label("Ranking", "Keeps longest without a freezer",
                        "top %d &middot; pantry and fridge on one scale"
                        % len(rows)))
    return out, by


def category_pages(accepted, cat_hubs):
    out = {}
    groups = {}
    for it, s, _n in accepted:
        groups.setdefault(it["category"], []).append((it, s))
    for cat, rows in sorted(groups.items()):
        c = cat_slug(cat)
        if c not in cat_hubs:
            continue
        # ПОРЯДОК ПО ТОМУ ЧИСЛУ, КОТОРОЕ НАПЕЧАТАНО В СТРОКЕ. Сортировка шла
        # по s["days"] (верхний край лучшего неморозильного окна), а строка
        # печатает осторожный край связывающего плюс «up to»: витрина,
        # объявленная «longest outside the freezer first», шла не по порядку
        # у всех на виду — shelf-stable «Canned goods · 3 days to 2 years»
        # стоял последним, ниже «Polenta · 5 days».
        rows.sort(key=lambda x: -(pr.listing_days(x[0]) or 0.0))
        tbl = rank_table([(it["slug"], title_of(it))
                          + pr.listing_parts(it) for it, s in rows])
        # СТРАНИЦА БЕЗ ЕДИНОГО ЧИСЛА НЕ ЗАКРЫВАЕТ РЕЙТИНГ. Такие продукты
        # (страницы-выбор и записи без срока) считались нулём и оказывались
        # последними, а абзац печатал их величину словом «unknown»: «closes
        # the list at unknown, a spread of almost nothing» стояло на пяти
        # витринах из тринадцати, при том что строкой выше честно напечатано
        # «Berries · 3 days to 7 days».
        rated = [r for r in rows if (pr.listing_days(r[0]) or 0.0) > 0]
        n_un = len(rows) - len(rated)
        tail = (" %s here %s kinds rather than one figure, so %s sit at the "
                "end without a place in the order."
                % (pr.plural_en(n_un, "page"),
                   pr.verb_n(n_un, "carries", "carry"),
                   "it" if n_un == 1 else "they")) if n_un else ""
        if rated:
            top, bot = rated[0], rated[-1]
            a = pr.listing_days(top[0]) or 0.0
            b = pr.listing_days(bot[0]) or 0.0
            span = (a / b) if b else 0
            # Числа в абзаце — ТЕ ЖЕ, что в строках над ним: величина,
            # названная в двух местах по-разному, однажды разойдётся.
            #
            # НИЧЬЯ — НЕ ПЕРВОЕ МЕСТО, И НЕ ПОСЛЕДНЕЕ. Сайт печатает на всех
            # 295 карточках собственное правило «identical ranges share a
            # place rather than being ordered arbitrarily», а витрины его
            # нарушали: на /category/food-purchased-frozen/ у ВСЕХ четырёх
            # еды ровно 3 дня, и «Pizza leads … Kugel closes the order»
            # назначались порядком в массиве. Восемь витрин из тринадцати.
            lead_n = sum(1 for r in rated
                         if abs((pr.listing_days(r[0]) or 0.0) - a) < 1e-9)
            tail_n = sum(1 for r in rated
                         if abs((pr.listing_days(r[0]) or 0.0) - b) < 1e-9)
            if lead_n == len(rated):
                said = ("Every food here keeps the same %s, so this page is a "
                        "tie rather than an order."
                        % esc(pr.listing_top_text(top[0])))
            else:
                head_txt = ("%s %s share the top at %s"
                            % (pr.plural_en(lead_n, "food"),
                               "here" if lead_n > 1 else "",
                               esc(pr.listing_top_text(top[0])))
                            if lead_n > 1 else
                            "%s leads at %s" % (esc(title_of(top[0])),
                                                esc(pr.listing_top_text(top[0]))))
                bot_txt = ("%s share the bottom at %s"
                           % (pr.plural_en(tail_n, "food"),
                              esc(pr.listing_top_text(bot[0])))
                           if tail_n > 1 else
                           "%s closes the order at %s"
                           % (esc(title_of(bot[0])),
                              esc(pr.listing_top_text(bot[0]))))
                said = ("%s and %s, a spread of %s across one shelf."
                        % (head_txt, bot_txt,
                           pr.mult(span) if span > 1.05 else "almost nothing"))
        else:
            said = "No food here carries a single figure to rank it by."
        body = (sect(tbl)
                + "<section><h2>How this list is ordered</h2>"
                  "<p>%d foods in this category have a page here, ranked by "
                  "the figure each row prints: how long it keeps outside the "
                  "freezer. %s%s</p></section>"
                  % (len(rows), said, tail))
        out["/category/%s/" % c] = shell(
            "/category/%s/" % c, "%s storage times" % cat,
            "How long %s %s, ranked: every USDA figure with the comparisons "
            "between them." % (cat.lower(), pr.keeps_word(cat)), body,
            wide=True, ptype="hub",
            src=esc(cat) + " &middot; USDA FoodKeeper",
            label=hub_label("Category", cat,
                            "%d foods &middot; longest outside the freezer "
                            "first" % len(rows)))
    return out


def all_index(accepted, cat_hubs):
    rows = sorted(accepted, key=lambda x: title_of(x[0]).lower())
    li = near_list([("/%s/" % it["slug"], title_of(it))
                    + pr.listing_parts(it) for it, _s, _n in rows])
    cats = {}
    for it, _s, _n in accepted:
        cats[it["category"]] = cats.get(it["category"], 0) + 1
    cl = near_list([("/category/%s/" % cat_slug(c), c, "%d foods" % n)
                    for c, n in sorted(cats.items())
                    if cat_slug(c) in cat_hubs])
    body = (sect("<h2>By category</h2>" + cl)
            + sect("<h2>Alphabetically</h2>" + li)
            + "<section><h2>How a food earns a page</h2>"
              "<p>%d foods, each with its own page. One page per name: where "
              "the USDA lists several kinds under one name, they share the "
              "page and every kind keeps its own windows. A name earns a page "
              "when the source gives it a window outside the freezer and at "
              "least %d neighbors to compare it against.</p></section>"
              % (len(rows), NEIGHBOURS[0]))
    return shell("/all/", "Every food on KeepsUntil",
                 "The complete index of foods with storage times on "
                 "KeepsUntil, by category and alphabetically.", body,
                 wide=True, ptype="hub",
                 src="Index &middot; USDA FoodKeeper",
                 label=hub_label("Index", "Every food on this site",
                                 "%d pages &middot; %d categories"
                                 % (len(rows), len(cats))))


# Поиск. ТРИ правила куплены замером на собранном сайте:
#
# 1. Запрос РЕЖЕТСЯ НА СЛОВА. Прежний склеивал запрос без пробелов и искал
#    подстроку в склеенном имени: «olive oil» не находил «Oils, olive or
#    vegetable», зато «salmon» находил «Roasted nuts (peanuts, cashews,
#    almonds)» — потому что в склейке «roastednutspeanutscashewsalmonds»
#    сидит «salmon». Порядок слов у источника обратный тому, которым говорят.
