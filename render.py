PAST_LINKS = 8


def _past_links(accepted):
    """Ссылки вглубь: продукты спроса, у которых окно — предел безопасности.

    Величина в строке — та же prose.listing_value, что и во всех списках
    сайта: третьего вида строки со сроком тут нет и быть не может.
    """
    by = {it["slug"]: it for it, _s, _n in accepted}
    rows = []
    for term in HEAD_TERMS:
        for slug, it in sorted(by.items()):
            if len(rows) >= PAST_LINKS:
                break
            if slug in [r[0] for r in rows]:
                continue
            need = set(re.findall(r"[a-z0-9]+", term.lower()))
            if need <= set(re.findall(r"[a-z0-9]+", it["name"].lower())) \
                    and pr.hot_kind(it) == fk.SAFETY:
                rows.append((slug, title_of(it)) + pr.listing_parts(it))
    return rank_table(rows, lead=False)


def sitemap(paths):
    lm = CONTENT_DATE.isoformat()
    urls = "".join("<url><loc>https://%s%s</loc><lastmod>%s</lastmod></url>"
                   % (DOMAIN, p, lm) for p in sorted(paths))
    return ('<?xml version="1.0" encoding="UTF-8"?>'
            '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">'
            "%s</urlset>" % urls)


def robots():
    return ("User-agent: *\nAllow: /\n\nSitemap: https://%s/sitemap.xml\n"
            % DOMAIN)


