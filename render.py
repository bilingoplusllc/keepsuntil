def house_creative(path, n):
    """Своя врезка в рекламном месте.

    Место, в котором нечего показать, — это либо пустая серая коробка с
    подписью «Advertisement» (322 страницы соседнего сайта), либо узел,
    спрятанный стилем, который всё равно остаётся ребёнком и ломает правила
    «последний теряет линию». Поэтому пока сеть не подключена, место занято
    НАШИМ, и подпись говорит, чьё это: выдать своё за оплаченное — обман.

    Ссылка на страницу, где человек уже стоит, — петля, поэтому текущий адрес
    из набора вычёркивается.
    """
    pool = [x for x in HOUSE_ADS if x[0] != path]
    href, head, line = pool[n % len(pool)]
    return ('<a class="house" href="%s"><span class="hcap">%s</span>'
            '<span class="hn">%s</span><span class="hsub">%s</span></a>'
            % (href, esc(HOUSE_CAP), esc(head), esc(line)))


def ad_tag(cls):
    """Разметка внешней сети. Собирается ТОЛЬКО при включённой сети.

    Номер издателя не подставляется по умолчанию и не выдумывается: чужой
    или пустой номер — это показы, отданные неизвестно кому. Нет номера —
    сборка падает здесь, а не отдаёт страницу с испорченным местом.
    """
    if AD_NETWORK not in AD_ORIGINS:
        raise ValueError("сеть %r не описана в AD_ORIGINS" % (AD_NETWORK,))
    if not AD_CLIENT:
        raise ValueError("сеть включена, а номер издателя не задан")
    unit = AD_UNITS.get(cls)
    if not unit:
        raise ValueError("для места %s не задан номер блока" % cls)
    return ('<ins class="adsbygoogle" style="display:block;width:100%%;'
            'height:100%%" data-ad-client="%s" data-ad-slot="%s"></ins>'
            % (AD_CLIENT, unit))


def ad_slot(cls, path, n):
    """Одно рекламное место — всегда с содержимым внутри."""
    body = ad_tag(cls) if AD_NETWORK else house_creative(path, n)
    return '<div class="ad %s">%s</div>' % (cls, body)


def ad_loader(n_slots):
    """Загрузчик сети и по одному толчку на место. Пусто, пока сети нет."""
    if not AD_NETWORK or not n_slots:
        return ""
    # Толчок печатается по одному на место, без цикла: знак «меньше» внутри
    # скрипта — ровно тот случай, где экранирование однажды съело код.
    push = "(adsbygoogle=window.adsbygoogle||[]).push({});" * n_slots
    return ('<script async src="%spagead/js/adsbygoogle.js?client=%s" '
            'crossorigin="anonymous"></script><script>%s</script>'
            % (AD_ORIGINS[AD_NETWORK][0], AD_CLIENT, push))


def _insert_after_sections(html, k, block):
    """Врезка ставится после k-го раздела корешка, а не поверх первого.

    На телефоне бирка с ответом и корешок идут встык, и место, поставленное
    сразу под перфорацией, оказалось бы вторым рекламным прямоугольником
    подряд после того, что стоит в бирке. Между ними обязан быть текст.
    """
    parts = html.split("</section>")
    if len(parts) <= k:
        return html + block
    return ("</section>".join(parts[:k]) + "</section>" + block
            + "</section>".join(parts[k:]))


def foot_row(path):
    """Подвал корешка: навигация и обязательная оговорка.

    Ссылка на текущую страницу заменяется текстом: петля — это когда человек
    нажимает и остаётся на месте.
    """
    nav = " &middot; ".join(
        ("<b>%s</b>" % txt) if href == path else
        ('<a href="%s">%s</a>' % (href, txt)) for href, txt in FOOT_LINKS)
    # Адреса почты в подвале больше нет. Он стоял на 302 страницах, и это
    # было две беды сразу: чужой ящик поддержки на витрине справочника и 302
    # места, где обфускация почты у Cloudflare переписывает отданное и
    # дописывает свой скрипт. Ссылка ведёт на страницу контактов, где адрес
    # напечатан один раз.
    # Пометка `data-shared` — ОБЪЯВЛЕНИЕ, а не украшение: по ней гейт
    # близнецов снимает подвал с полного текста страницы, не угадывая его по
    # словам. Что снято из сравнения, обязано быть видно в разметке.
    return ('<section data-shared><p class="quiet">%s</p></section>'
            '<footer class="foot">%s<br>&copy; %d %s &middot; Data: %s</footer>'
            % (esc(DISCLAIMER), nav, CONTENT_DATE.year, FOOT_NAME,
               esc(DATA_VINTAGE)))


